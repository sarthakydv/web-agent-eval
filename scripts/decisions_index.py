"""Generate (or check) the entry index at the top of docs/DECISIONS.md.

    uv run python scripts/decisions_index.py           # rewrite the index
    uv run python scripts/decisions_index.py --check    # exit 1 if it is stale

The index exists so a session can find the entry it needs without reading the
whole log. The log is append-only and grows with the project — that is correct
behaviour, and it is why nothing may instruct a runner to read it end to end.

It is generated from the `## N — title` headings rather than maintained by hand,
because a hand-written index of an append-only file drifts the first time
someone appends in a hurry, and a stale index is worse than none: it is trusted.
`init.sh` runs --check.
"""

import re
import sys
from pathlib import Path

DOC = Path(__file__).resolve().parent.parent / "docs" / "DECISIONS.md"
BEGIN = "<!-- INDEX:BEGIN — generated by scripts/decisions_index.py, do not edit by hand -->"
END = "<!-- INDEX:END -->"

HEADING = re.compile(r"^## (\d+) — (.+)$")
DATE = re.compile(r"^\*\*Date:\*\*\s*(\S+)")


def build_index(text: str) -> str:
    lines = text.splitlines()
    rows = []
    for i, line in enumerate(lines):
        m = HEADING.match(line)
        if not m:
            continue
        number, title = m.group(1), m.group(2).strip()
        date = ""
        for peek in lines[i + 1 : i + 8]:
            d = DATE.match(peek)
            if d:
                date = d.group(1)
                break
        rows.append(f"- **{number}** ({date or 'undated'}) — {title}")
    body = "\n".join(rows) if rows else "_no entries yet_"
    return f"{BEGIN}\n\n### Entries\n\n{body}\n\n{END}"


def splice(text: str, index: str) -> str:
    if BEGIN in text and END in text:
        start = text.index(BEGIN)
        stop = text.index(END) + len(END)
        return text[:start] + index + text[stop:]
    # First run: place the index after the file's opening paragraph, before the
    # first horizontal rule.
    marker = "\n---\n"
    cut = text.index(marker)
    return text[:cut] + "\n" + index + "\n" + text[cut:]


def main() -> int:
    text = DOC.read_text()
    index = build_index(text)
    updated = splice(text, index)
    # Count the index's own rows. Counting "- **" over the whole document would
    # also catch bold bullets inside entry bodies, which is how a count ends up
    # reporting 16 entries for an 8-entry log.
    count = sum(1 for line in index.splitlines() if line.startswith("- **"))

    if "--check" in sys.argv:
        if updated != text:
            print("  FAIL: docs/DECISIONS.md index is stale — run scripts/decisions_index.py")
            return 1
        print(f"  decisions: index current, {count} entries")
        return 0

    DOC.write_text(updated)
    print(f"index written: {count} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
